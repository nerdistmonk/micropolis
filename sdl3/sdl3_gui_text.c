static TTF_Font *LoadFont(const char *name, float pt)
{
    const char *dirs[] = { "fonts/", "../fonts/", "../../fonts/", "res/fonts/" };
    char path[512];
    for (size_t i = 0; i < sizeof(dirs) / sizeof(dirs[0]); i++) {
        snprintf(path, sizeof(path), "%s%s", dirs[i], name);
        FILE *f = fopen(path, "rb");
        if (f) {
            fclose(f);
            TTF_Font *font = TTF_OpenFont(path, pt);
            if (font) return font;
        }
    }
    return NULL;
}

bool GUI_Text_Init(void)
{
    if (!TTF_Init()) {
        SDL_Log("Warning: TTF_Init failed: %s. Using 8x8 fallback bitmap font.", SDL_GetError());
        return false;
    }

    font_main = LoadFont("DejaVuLGCSans-Bold.ttf", 12.0f);
    return (font_main != NULL);
}

void GUI_Text_Shutdown(void)
{
    if (font_main) {
        TTF_CloseFont(font_main);
        font_main = NULL;
    }
    TTF_Quit();
}

int GUI_GetTextWidth(const char *text)
{
    if (!text || text[0] == '\0') return 0;
    if (font_main) {
        int w = 0, h = 0;
        TTF_GetStringSize(font_main, text, strlen(text), &w, &h);
        return w;
    }
    return (int)strlen(text) * 8;
}

void GUI_DrawText(SDL_Renderer *renderer, int x, int y, const char *text, SDL_Color color)
{
    if (!renderer || !text || text[0] == '\0') return;

    if (font_main) {
        SDL_Surface *surf = TTF_RenderText_Blended(font_main, text, 0, color);
        if (surf) {
            SDL_Texture *tex = SDL_CreateTextureFromSurface(renderer, surf);
            if (tex) {
                SDL_FRect dst = { (float)x, (float)y, (float)surf->w, (float)surf->h };
                SDL_RenderTexture(renderer, tex, NULL, &dst);
                SDL_DestroyTexture(tex);
            }
            SDL_DestroySurface(surf);
            return;
        }
    }

    /* Drop shadow fallback */
    SDL_SetRenderDrawColor(renderer, 10, 10, 15, 255);
    int cur_x = x + 1;
    const char *ptr = text;
    while (*ptr) {
        char c = *ptr++;
        if (c < 32 || c > 126) c = '?';
        const uint8_t *glyph = font8x8_basic[c - 32];
        for (int row = 0; row < 8; row++) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    SDL_RenderPoint(renderer, (float)(cur_x + col), (float)(y + 1 + row));
                }
            }
        }
        cur_x += 8;
    }

    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    cur_x = x;
    ptr = text;
    while (*ptr) {
        char c = *ptr++;
        if (c < 32 || c > 126) c = '?';
        const uint8_t *glyph = font8x8_basic[c - 32];
        for (int row = 0; row < 8; row++) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    SDL_RenderPoint(renderer, (float)(cur_x + col), (float)(y + row));
                }
            }
        }
        cur_x += 8;
    }
}